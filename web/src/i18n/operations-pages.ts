export function operationsText(locale: Locale, english: string, values: Record<string, string | number> = {}): string {
  let result = locale === "ru" ? (russian[english] ?? english) : english;
  for (const [key, value] of Object.entries(values)) result = result.replaceAll(`{${key}}`, String(value));
  return result;
}
